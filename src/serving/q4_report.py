        f"result but leaves {next(x for x in me['loader_residue'] if x['loader'] == 'provided_word2vec')['rss_left_behind_mb']:.0f} MB "
        f"behind. A production server would load prebuilt serving artifacts instead.",
        "",
        "### 4.3 Latency",
        "",
        f"Over {d['lat_mind']['n_requests']:,} replayed test requests per dataset, one request takes **p50 "
