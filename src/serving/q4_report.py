#!/usr/bin/env python3
"""Q4 phase 6: write the Q4 tables and design-note section from the measured JSON.

Every number in the two outputs is read from reports/q4_*.json, so the prose can
never drift from the measurements; re-running any phase and then this script
refreshes both documents.

  reports/q4_summary.md      all Q4 tables (setup, correctness, memory, latency,
                             cost, 10x scale) with assumptions and caveats
  reports/design_note_q4.md  the Q4 section of the design note (Q6)

Usage
-----
    python src/serving/q4_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

REPORTS = REPO_ROOT / "reports"
DATASETS = ("mind", "ebnerd")
LABEL = {"mind": "MIND-small", "ebnerd": "EB-NeRD small"}
STAGES = ("profile", "bm25", "faiss", "popularity", "merge", "features", "nrms", "sort")
WHAT = {  # dataset-neutral descriptions; the per-dataset JSON "what" strings embed MIND/EB-NeRD sizes
    "stage1/faiss_flat_index (pool)": "exact FAISS index over the circulating pool",
    "stage1/a1_article_embeddings": "A1 article embeddings (float32), for each user's query vector",
    "stage1/bm25_weights (doc x term)": "sparse BM25 weight matrix",
    "stage1/bm25_weights_t (term x doc)": "the same weights transposed, kept for fast scoring",
    "stage1/bm25_vocabulary": "term → column dict",
    "stage1/bm25_other": "idf, document ids and lengths",
    "stage1/popularity_ranker": "train-click ranking",
    "stage1/pool_index": "circulating-pool rows + id set",
    "stage1/article_tokens+ids": "article tokens BM25 queries are built from",
    "stage1/user_profile_store": "every user's full click history",
    "cache/bm25_pooled_weights_t": "pool-sliced BM25 matrix, built once",
    "cache/tokens_by_id": "article → tokens dict, built once",
    "cache/popularity_top_k": "static popularity top-20, built once",
    "stage2/nrms_parameters": "NRMS weights (float32)",
    "stage2/nrms_title_token_table": "title token ids, only needed to encode new articles",
    "stage2/article_vectors": "every article's NRMS vector, precomputed at start-up",
    "stage2/nrms_row_index": "article id → row dict",
    "stage2/click_timeline": "one int64 per click (popularity counts)",
    "stage2/publish_times": "float64 per article (freshness)",
}


def load(name: str) -> dict:
    return json.loads((REPORTS / name).read_text(encoding="utf-8"))


def f(x, nd=2) -> str:
    return f"{x:,.{nd}f}"


def table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out + [""]


def collect() -> dict:
    d = {"env": load("q4_environment.json"), "cost": load("q4_cost.json"),
         "repeat": load("q4_latency_repeatability.json")}
    for ds in DATASETS:
        d[f"correct_{ds}"] = load(f"q4_correctness_{ds}.json")
        d[f"mem_{ds}"] = load(f"q4_memory_{ds}.json")
        d[f"lat_{ds}"] = load(f"q4_latency_{ds}.json")
        d[f"scale_{ds}"] = load(f"q4_scale_{ds}.json")
    return d


def cost_row(d, ds, mode, qps, slowdown=1):
    return next(r for r in d["cost"]["datasets"][ds]["modes"][mode]["table"]
                if r["qps"] == qps and r["cloud_slowdown"] == slowdown)


